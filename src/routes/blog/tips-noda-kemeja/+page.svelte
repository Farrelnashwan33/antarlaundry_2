				<div class="prose prose-primary max-w-none text-surface-700">
					<p class="mb-6 text-lg leading-relaxed">
						Pakaian putih adalah andalan di lemari pakaian banyak orang, namun menjaganya tetap
						bersih seringkali menjadi tantangan tersendiri. Terutama ketika kemeja kesayangan Anda
						terkena noda membandel seperti kopi, saus, atau tinta.
					</p>

					<h2 class="mt-8 mb-4 text-2xl font-bold text-surface-900">
						1. Tangani Noda Secepat Mungkin
					</h2>
					<p class="mb-6 leading-relaxed">
						Kunci utama menghilangkan noda adalah kecepatan. Jangan tunggu noda mengering dan
						meresap ke dalam serat kain. Segera bilas area yang terkena noda dengan air dingin
						(jangan gunakan air panas karena dapat membuat beberapa jenis noda semakin melekat).
					</p>

					<h2 class="mt-8 mb-4 text-2xl font-bold text-surface-900">
						2. Gunakan Bahan Alami (Baking Soda & Cuka)
					</h2>
					<p class="mb-6 leading-relaxed">
						Campurkan baking soda dan cuka putih hingga membentuk pasta. Oleskan pasta tersebut
						tepat di atas noda dan biarkan selama 15-30 menit. Cuka akan membantu melarutkan noda,
						sementara sifat abrasif lembut dari baking soda akan mengangkat kotoran dari serat.
					</p>

					<h2 class="mt-8 mb-4 text-2xl font-bold text-surface-900">
						3. Cuci dengan Suhu Air yang Tepat
					</h2>
					<p class="mb-6 leading-relaxed">
						Setelah *pre-treatment*, cucilah kemeja putih Anda menggunakan deterjen berkualitas.
						Jika kain memungkinkan (baca label pakaian), gunakan air hangat atau panas untuk
						melarutkan sisa noda secara sempurna.
					</p>

