          <p class="text-lg mb-6 leading-relaxed">Bumi adalah satu-satunya tempat tinggal kita. Di Antar Laundry, kami menyadari bahwa industri binatu (laundry) secara historis memiliki dampak signifikan terhadap penggunaan air dan limbah kimia kimia. Oleh karena itu, kami berkomitmen untuk melakukan perubahan.</p>
          
          <h2 class="text-2xl font-bold text-surface-900 mt-8 mb-4">Penggunaan Deterjen Bio-Degradable</h2>
          <p class="mb-6 leading-relaxed">Mulai kuartal ketiga tahun ini, seluruh cabang operasional Antar Laundry telah 100% beralih menggunakan deterjen bio-degradable (mudah terurai oleh alam). Produk pembersih kami kini bebas dari fosfat dan bahan kimia keras lainnya, sehingga limbah air hasil cucian lebih aman saat dikembalikan ke saluran pembuangan kota.</p>
          
          <h2 class="text-2xl font-bold text-surface-900 mt-8 mb-4">Efisiensi Penggunaan Air</h2>
          <p class="mb-6 leading-relaxed">Kami juga telah meng-upgrade mesin-mesin industri kami ke teknologi *High Efficiency* (HE) yang mengkonsumsi 40% air lebih sedikit dibandingkan mesin tradisional, tanpa mengurangi kebersihan hasil cucian.</p>
          
          <h2 class="text-2xl font-bold text-surface-900 mt-8 mb-4">Langkah Selanjutnya</h2>
